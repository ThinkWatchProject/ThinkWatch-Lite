//! 一套 5×7 的点阵字形。
//!
//! **为什么手写而不是用字体光栅化器**：菜单栏那块只有 22pt 高，两行文字
//! 各自只有 7px 的字高。真字体在这个尺寸下会糊成一团（hinting 救不了
//! 7px），而点阵字形是像素级确定的 —— 每个数字宽度严格相同，直接解决了
//! 那条「宽度抖动」：花费从 `$9.99` 跳到 `$10.02` 时，右边的图标
//! 不该跟着左右移动。
//!
//! 代价是字符集有限。这里只覆盖菜单栏会用到的那些（指标表）。

/// 每个字形 7 行，每行低 5 位有效，从最高位（左）到低位（右）。
pub const GLYPH_W: usize = 5;
pub const GLYPH_H: usize = 7;

/// 字距。1px 已经够分开，而菜单栏每一像素都金贵（刘海机型）。
pub const TRACKING: usize = 1;

#[rustfmt::skip]
fn glyph(c: char) -> Option<[u8; GLYPH_H]> {
    Some(match c {
        '0' => [0b01110, 0b10001, 0b10011, 0b10101, 0b11001, 0b10001, 0b01110],
        '1' => [0b00100, 0b01100, 0b00100, 0b00100, 0b00100, 0b00100, 0b01110],
        '2' => [0b01110, 0b10001, 0b00001, 0b00010, 0b00100, 0b01000, 0b11111],
        '3' => [0b11111, 0b00010, 0b00100, 0b00010, 0b00001, 0b10001, 0b01110],
        '4' => [0b00010, 0b00110, 0b01010, 0b10010, 0b11111, 0b00010, 0b00010],
        '5' => [0b11111, 0b10000, 0b11110, 0b00001, 0b00001, 0b10001, 0b01110],
        '6' => [0b00110, 0b01000, 0b10000, 0b11110, 0b10001, 0b10001, 0b01110],
        '7' => [0b11111, 0b00001, 0b00010, 0b00100, 0b01000, 0b01000, 0b01000],
        '8' => [0b01110, 0b10001, 0b10001, 0b01110, 0b10001, 0b10001, 0b01110],
        '9' => [0b01110, 0b10001, 0b10001, 0b01111, 0b00001, 0b00010, 0b01100],
        '$' => [0b00100, 0b01111, 0b10100, 0b01110, 0b00101, 0b11110, 0b00100],
        '.' => [0b00000, 0b00000, 0b00000, 0b00000, 0b00000, 0b01100, 0b01100],
        ',' => [0b00000, 0b00000, 0b00000, 0b00000, 0b01100, 0b00100, 0b01000],
        '%' => [0b11001, 0b11010, 0b00010, 0b00100, 0b01000, 0b01011, 0b10011],
        '/' => [0b00001, 0b00010, 0b00010, 0b00100, 0b01000, 0b01000, 0b10000],
        ':' => [0b00000, 0b01100, 0b01100, 0b00000, 0b01100, 0b01100, 0b00000],
        '-' => [0b00000, 0b00000, 0b00000, 0b11111, 0b00000, 0b00000, 0b00000],
        // 「没有数据」用长破折号，比 0 诚实 —— 0 是一个值，破折号不是
        '—' => [0b00000, 0b00000, 0b00000, 0b11111, 0b00000, 0b00000, 0b00000],
        '?' => [0b01110, 0b10001, 0b00001, 0b00010, 0b00100, 0b00000, 0b00100],
        '!' => [0b00100, 0b00100, 0b00100, 0b00100, 0b00100, 0b00000, 0b00100],
        't' => [0b01000, 0b01000, 0b11100, 0b01000, 0b01000, 0b01001, 0b00110],
        's' => [0b00000, 0b00000, 0b01111, 0b10000, 0b01110, 0b00001, 0b11110],
        'k' => [0b10000, 0b10000, 0b10010, 0b10100, 0b11000, 0b10100, 0b10010],
        'M' => [0b10001, 0b11011, 0b10101, 0b10101, 0b10001, 0b10001, 0b10001],
        'G' => [0b01110, 0b10001, 0b10000, 0b10111, 0b10001, 0b10001, 0b01111],
        'm' => [0b00000, 0b00000, 0b11010, 0b10101, 0b10101, 0b10101, 0b10101],
        // 活跃流的三角，和「在动」这件事同构
        '▶' => [0b10000, 0b11000, 0b11100, 0b11110, 0b11100, 0b11000, 0b10000],
        // 输入速率的上箭头（脉冲式指标）
        '↑' => [0b00100, 0b01110, 0b10101, 0b00100, 0b00100, 0b00100, 0b00100],
        '·' => [0b00000, 0b00000, 0b00000, 0b01100, 0b01100, 0b00000, 0b00000],
        ' ' => [0, 0, 0, 0, 0, 0, 0],
        _ => return None,
    })
}

/// 这个字符画不出来吗。
///
/// **调用方必须处理**：画不出来时应该换一个能画的写法，而不是画一个
/// 方块或者直接跳过 —— 前者难看，后者会让 `$10.02` 变成 `$1002`，那是
/// 一个**错误的数字**。
pub fn can_render(c: char) -> bool {
    glyph(c).is_some()
}

/// 一段文字画出来有多宽（像素）。
pub fn text_width(s: &str) -> usize {
    let n = s.chars().count();
    if n == 0 {
        return 0;
    }
    n * GLYPH_W + (n - 1) * TRACKING
}

/// 把一段文字画进一个 alpha 缓冲区（`w × h`，每字节一个像素的覆盖度）。
///
/// 越界的部分直接裁掉 —— 菜单栏宁可少画一个字，也不该 panic。
pub fn draw_text(buf: &mut [u8], w: usize, h: usize, x0: i32, y0: i32, s: &str) {
    let mut x = x0;
    for c in s.chars() {
        if let Some(g) = glyph(c) {
            for (row, bits) in g.iter().enumerate() {
                let y = y0 + row as i32;
                if y < 0 || y as usize >= h {
                    continue;
                }
                for col in 0..GLYPH_W {
                    // 最高位在左
                    if bits & (1 << (GLYPH_W - 1 - col)) != 0 {
                        let px = x + col as i32;
                        if px >= 0 && (px as usize) < w {
                            buf[y as usize * w + px as usize] = 255;
                        }
                    }
                }
            }
        }
        x += (GLYPH_W + TRACKING) as i32;
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_digit_has_a_glyph_and_they_are_all_the_same_width() {
        // 等宽是「宽度抖动」那条的全部依据：$9.99 变 $10.02 时，右边的
        // 图标不该跟着动。
        for c in "0123456789".chars() {
            assert!(can_render(c), "{c} 没有字形");
        }
        assert_eq!(text_width("9.99"), text_width("0.00"));
        assert_eq!(text_width("$10.02"), text_width("$99.99"));
    }

    #[test]
    fn the_metrics_from_the_design_table_are_all_renderable() {
        // 那张指标表里的每一种写法都要能画。画不出来的话，调用方
        // 会静默跳过那个字符 —— 而 $10.02 变成 $1002 是一个错误的数字。
        for s in [
            "$3.42", "47 t/s", "↑2.1k", "3 ▶", "1.2M", "73%", "840ms", "—",
        ] {
            for c in s.chars() {
                assert!(can_render(c), "{s:?} 里的 {c:?} 画不出来");
            }
        }
    }

    #[test]
    fn drawing_outside_the_canvas_clips_instead_of_panicking() {
        let (w, h) = (20, 10);
        let mut buf = vec![0u8; w * h];
        // 四个方向都越界
        draw_text(&mut buf, w, h, -50, 0, "123");
        draw_text(&mut buf, w, h, 100, 0, "123");
        draw_text(&mut buf, w, h, 0, -50, "123");
        draw_text(&mut buf, w, h, 0, 100, "123");
    }

    #[test]
    fn a_drawn_glyph_actually_marks_pixels() {
        let (w, h) = (20, 10);
        let mut buf = vec![0u8; w * h];
        draw_text(&mut buf, w, h, 0, 0, "8");
        assert!(buf.iter().any(|&p| p > 0), "什么都没画出来");
    }

    #[test]
    fn unknown_characters_advance_the_cursor_so_layout_stays_aligned() {
        // 画不出来的字符仍然占位。跳过它会让后面的字挤上来，而那在
        // 数字里就是一个错误的读数。
        let (w, h) = (60, 10);
        let mut a = vec![0u8; w * h];
        let mut b = vec![0u8; w * h];
        draw_text(&mut a, w, h, 0, 0, "1@2");
        draw_text(&mut b, w, h, 0, 0, "1 2");
        assert_eq!(a, b, "未知字符应该和空格占一样的位置");
    }
}
