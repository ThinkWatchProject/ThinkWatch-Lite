/**
 * 只认最后一次的异步请求：发出时领一个号，回来时号已经不是最新的，结果就扔掉。
 *
 * 用在「按发出那一刻的表单去问、回来时表单可能已经改了」的请求上（上游对话框的检测
 * 连接）：改了密钥之后才回来的那次检测，测的是改之前的密钥，它说的「连接正常」
 * 不能挂在新密钥下面。`drop()` 让还没回来的全部作废，表单一改就调它。
 */
export function latestOnly(): {
  /** 发出一次。回来时调返回的函数：还是最新的那一次吗 */
  start: () => () => boolean;
  /** 已经发出、还没回来的全部作废 */
  drop: () => void;
} {
  let n = 0;
  return {
    start() {
      n += 1;
      const mine = n;
      return () => mine === n;
    },
    drop() {
      n += 1;
    },
  };
}
